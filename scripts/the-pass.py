MONO = 'font-family="IBM Plex Mono, monospace"'

def marker():
    return ('<defs><marker id="ar" viewBox="0 0 10 10" refX="9" refY="5" '
            'markerWidth="7" markerHeight="7" orient="auto-start-reverse">'
            '<path d="M 0 0 L 10 5 L 0 10 z" fill="currentColor"/></marker></defs>')

def box(x, y, w, h, *, stroke="currentColor", var=None, sw=1, dash=None, op=None):
    s = f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="none" stroke="{stroke}"'
    if var:
        s += f' style="stroke:var(--{var})"'
    s += f' stroke-width="{sw}"'
    if dash:
        s += f' stroke-dasharray="{dash}"'
    if op:
        s += f' opacity="{op}"'
    return s + "/>"

def txt(x, y, t, *, size=12.5, anchor="middle", mono=False, var=None, op=None,
        ls=None, weight=None, transform=None):
    s = f'<text x="{x}" y="{y}" text-anchor="{anchor}" font-size="{size}"'
    if mono:
        s += " " + MONO
    s += ' fill="currentColor"'
    if var:
        s += f' style="fill:var(--{var})"'
    if op:
        s += f' opacity="{op}"'
    if ls:
        s += f' letter-spacing="{ls}"'
    if weight:
        s += f' font-weight="{weight}"'
    if transform:
        s += f' transform="{transform}"'
    return s + f">{t}</text>"

def line(x1, y1, x2, y2, *, arrow=True, op=".55", var=None, dash=None, sw=1):
    s = f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="currentColor"'
    if var:
        s += f' style="stroke:var(--{var})"'
    s += f' stroke-width="{sw}" opacity="{op}"'
    if dash:
        s += f' stroke-dasharray="{dash}"'
    if arrow:
        s += ' marker-end="url(#ar)"'
    return s + "/>"

def poly(pts, *, arrow=True, op=".55", var=None):
    p = " ".join(f"{a},{b}" for a, b in pts)
    s = f'<polyline points="{p}" fill="none" stroke="currentColor"'
    if var:
        s += f' style="stroke:var(--{var})"'
    s += f' stroke-width="1" opacity="{op}"'
    if arrow:
        s += ' marker-end="url(#ar)"'
    return s + "/>"


