# ---------------------------------------------------------------- figure one
# Ten steps, and the geometry is computed from the list rather than typed.
# Hand-placed coordinates were fine for five; at ten they are a source of
# defects that no test would catch.
BX, BW = 270, 340              # the spine
CX = BX + BW / 2
TOP, PITCH, BH = 30, 78, 46    # first step, step-to-step, box height
RET = 176                      # proposed's returns, to the left of the scope
FAN = 648                      # what did not pass, to the right of the spine
RX, RW = 706, 226              # waiting on you, outside the worktree

def _y(i):
    return TOP + i * PITCH

def figure_one(T):
    o = [marker()]
    a = o.append
    steps = T["f1_steps"]                       # (name, under, refuses)
    n = len(steps)
    bottom = _y(n - 1) + BH

    # the worktree's scope: cut at admit, alive past the merge lane
    a(box(BX - 58, _y(1) - 12, BW + 116, _y(n - 2) + BH + 12 - (_y(1) - 12),
          var="prop", sw=2, dash="7 5"))
    a(txt(BX - 58, _y(1) - 18, T["f1_scope"], size=10.5, mono=True,
          anchor="start", var="prop", ls="1.3"))

    for i, (name, under, refuses) in enumerate(steps):
        y = _y(i)
        strong = name == "implement"
        a(box(BX, y, BW, BH, var="brass" if refuses else None,
              sw=2.5 if strong else (2 if refuses else 1.5)))
        a(txt(BX + 14, y + 20, "%d/%d" % (i + 1, n), size=11, mono=True,
              anchor="start", var="brass" if refuses else "faint", ls="1.2"))
        a(txt(CX, y + 20, name, size=13.5 if strong else 13, mono=True,
              var="brass" if refuses else None))
        a(txt(CX, y + 37, under, size=11.5, op=".62"))
        if i + 1 < n:
            a(line(CX, y + BH, CX, _y(i + 1)))

    # what did not pass: a stub from each such step into one channel, and one
    # arrow into proposed. Seven edges drawn as seven stubs and a rule.
    idx = {name: k for k, (name, _, _) in enumerate(steps)}
    po = idx["proposed"]
    for name in ("admit", "prepared", "design", "implement", "build", "review"):
        y = _y(idx[name]) + BH / 2
        a(line(BX + BW, y, FAN, y, arrow=False, op=".55", dash="4 4"))
    a(line(BX + BW, _y(idx["merge"]) + BH / 2, FAN,
           _y(idx["merge"]) + BH / 2, arrow=False, op=".55", dash="4 4"))
    a(line(FAN, _y(idx["admit"]) + BH / 2, FAN, _y(idx["merge"]) + BH / 2,
           arrow=False, op=".55", dash="4 4"))
    a(line(FAN, _y(po) + BH / 2, BX + BW + 2, _y(po) + BH / 2, op=".75"))
    a(txt(FAN + 14, _y(idx["design"]) + 18, T["f1_fan"], size=11.5, op=".7",
          anchor="start"))
    a(txt(FAN + 14, _y(idx["design"]) + 34, T["f1_fan2"], size=10.5, op=".55",
          anchor="start"))

    # proposed's returns, on the left
    a(line(BX, _y(po) + BH / 2, RET, _y(po) + BH / 2, arrow=False,
           op=".75", var="prop"))
    a(line(RET, _y(po) + BH / 2, RET, _y(idx["build"]) + 14, arrow=False,
           op=".75", var="prop"))
    for name, dy in (("build", 14), ("implement", 24), ("claim", 34)):
        a(line(RET, _y(idx[name]) + dy, BX - 2, _y(idx[name]) + dy, op=".75",
               var="prop"))
    a(line(RET, _y(idx["build"]) + 14, RET, _y(idx["claim"]) + 34,
           arrow=False, op=".75", var="prop"))
    ry = (_y(idx["build"]) + _y(idx["claim"])) / 2 + 24
    a(txt(RET - 14, ry, T["f1_ret1"], size=11.5, var="prop",
          transform="rotate(-90 %d %d)" % (RET - 14, ry)))
    for name, dy, key in (("build", 14, "f1_ret_build"),
                          ("implement", 24, "f1_ret_impl"),
                          ("claim", 34, "f1_ret_claim")):
        a(txt(RET + 8, _y(idx[name]) + dy - 5, T[key], size=10.5, anchor="start",
              op=".62"))

    # waiting on you — brass is only ever a person
    wy = _y(po) + BH + 16
    a(box(RX, wy, RW, BH, var="brass", sw=2))
    a(txt(RX + RW / 2, wy + 20, T["f1_wait"], size=13, mono=True, var="brass"))
    a(txt(RX + RW / 2, wy + 37, T["f1_wait2"], size=11, op=".62"))
    a(poly([(BX + BW, _y(po) + BH - 8), (FAN + 30, _y(po) + BH - 8),
            (FAN + 30, wy + BH / 2), (RX - 2, wy + BH / 2)]))
    a(txt(RX + RW / 2, wy - 8, T["f1_spent"], size=10.5, op=".62"))

    # and waiting reaches end, because end runs on every outcome
    ey = _y(idx["end"]) + BH / 2
    a(poly([(RX + RW / 2, wy + BH), (RX + RW / 2, ey), (BX + BW + 2, ey)],
           op=".55"))
    a(txt(RX + RW / 2 + 10, ey - 8, T["f1_closed"], size=10.5, op=".62",
          anchor="start"))

    return ('<svg viewBox="0 0 980 %d" role="img" aria-label="%s">%s</svg>'
            % (bottom + 28, T["f1_alt"], "".join(o)))


